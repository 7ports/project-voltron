#!/usr/bin/env node
// voltron-evals/tools/generate-instances.js
//
// Stage 5: reads `voltron-evals/coverage-map.yaml` and emits one Broad-layer
// instance YAML per agent under `voltron-evals/instances/<shape>/<agent>.yaml`.
//
// Each emitted instance uses the new schema the runner now consumes:
//   kind: broad
//   extends: <shape-rel-path>
//   parameters: { ... }
//
// The script is deterministic: same coverage-map input → same output bytes.
// Run after changing the coverage map to refresh the instance set.
//
// Usage:
//   node voltron-evals/tools/generate-instances.js          # write under voltron-evals/instances/
//   node voltron-evals/tools/generate-instances.js --check  # exit 1 if any file would change
//   node voltron-evals/tools/generate-instances.js --clean  # remove instance/<shape>/ subdirs first

import { promises as fs } from "node:fs";
import { readFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseYaml, stringify as stringifyYaml } from "yaml";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..", "..");
const MAP_PATH = path.join(REPO_ROOT, "voltron-evals", "coverage-map.yaml");
const INSTANCES_DIR = path.join(REPO_ROOT, "voltron-evals", "instances");

function header(shapeId, agent, extendsPath) {
  return [
    `# voltron-evals/instances/${shapeId}/${agent}.yaml`,
    "#",
    `# Generated by voltron-evals/tools/generate-instances.js from coverage-map.yaml.`,
    `# Do NOT edit by hand — re-run the generator after updating the map.`,
    "",
  ].join("\n");
}

function buildInstance(shapeId, extendsPath, agent, entry) {
  const params = {
    agent_under_test: agent,
  };
  if (entry.prompt_inputs !== undefined) params.prompt_inputs = entry.prompt_inputs;
  if (entry.fixture !== undefined) params.fixture = entry.fixture;
  if (entry.expected_files !== undefined) params.expected_files = entry.expected_files;
  if (entry.forbidden_files !== undefined) params.forbidden_files = entry.forbidden_files;
  if (entry.canonical_action !== undefined) params.canonical_action = entry.canonical_action;
  if (entry.test_command !== undefined) params.test_command = entry.test_command;
  if (entry.expected_beads_floor !== undefined) params.expected_beads_floor = entry.expected_beads_floor;
  if (entry.source_globs !== undefined) params.source_globs = entry.source_globs;
  if (entry.line_caps !== undefined) params.line_caps = entry.line_caps;
  if (entry.dispatch_floor !== undefined) params.dispatch_floor = entry.dispatch_floor;
  if (entry.max_turns !== undefined) params.max_turns = entry.max_turns;

  const inst = {
    kind: "broad",
    extends: extendsPath,
    id: `${shapeId}/${agent}`,
    parameters: params,
  };
  return inst;
}

async function rmrf(dir) {
  if (!existsSync(dir)) return;
  await fs.rm(dir, { recursive: true, force: true });
}

async function main() {
  const args = new Set(process.argv.slice(2));
  const checkOnly = args.has("--check");
  const cleanFirst = args.has("--clean");

  const map = parseYaml(readFileSync(MAP_PATH, "utf-8"));
  if (!map || !map.shapes) {
    throw new Error("coverage-map.yaml missing 'shapes' top-level key");
  }

  if (cleanFirst && !checkOnly) {
    for (const shapeId of Object.keys(map.shapes)) {
      await rmrf(path.join(INSTANCES_DIR, shapeId));
    }
  }

  let written = 0;
  let drift = 0;
  let totalAgents = 0;
  const writtenPaths = [];

  for (const [shapeId, shapeBlock] of Object.entries(map.shapes)) {
    const extendsPath = shapeBlock.extends;
    if (!extendsPath) {
      throw new Error(`coverage-map.yaml: shape '${shapeId}' missing 'extends:' path`);
    }
    const agents = shapeBlock.agents || {};
    for (const [agent, entry] of Object.entries(agents)) {
      totalAgents++;
      const inst = buildInstance(shapeId, extendsPath, agent, entry);
      const outDir = path.join(INSTANCES_DIR, shapeId);
      const outPath = path.join(outDir, `${agent}.yaml`);
      const body = stringifyYaml(inst, { lineWidth: 0 });
      const fileContents = header(shapeId, agent, extendsPath) + body;

      if (checkOnly) {
        const cur = existsSync(outPath) ? readFileSync(outPath, "utf-8") : null;
        if (cur !== fileContents) {
          drift++;
          process.stdout.write(`[DRIFT] ${path.relative(REPO_ROOT, outPath)}\n`);
        }
      } else {
        await fs.mkdir(outDir, { recursive: true });
        await fs.writeFile(outPath, fileContents, "utf-8");
        written++;
        writtenPaths.push(path.relative(REPO_ROOT, outPath));
      }
    }
  }

  if (checkOnly) {
    if (drift) {
      process.stdout.write(`[CHECK] ${drift} file(s) out of date — run generate-instances.js without --check to refresh.\n`);
      process.exit(1);
    }
    process.stdout.write(`[CHECK] OK — ${totalAgents} instances all up to date.\n`);
    return;
  }

  process.stdout.write(`Generated ${written} instance file(s) across ${Object.keys(map.shapes).length} shape(s).\n`);
  if (map.excluded?.length) {
    process.stdout.write(`Excluded agents: ${map.excluded.map(e => e.name).join(", ")}\n`);
  }
}

main().catch(err => { console.error(err); process.exit(2); });
